import { expect, test } from '@playwright/test'

test('protocol handoff persists across readiness route before medical certification', async ({ page }) => {
  await page.goto('/studies/TF-201/subjects/S-014/timeline')
  await page.getByRole('button', { name: 'Record visit' }).click()
  await page.getByRole('button', { name: 'Record protocol amendment' }).click()
  await page.getByRole('button', { name: 'Request medical review' }).click()
  await expect(page.getByLabel('Medical review inbox')).toContainText('medical reviewer · open')
  await page.goto('/studies/TF-201/subjects/S-014/readiness')
  await expect(page.getByRole('button', { name: 'Authorize next visit' })).toBeDisabled()
  await page.goto('/studies/TF-201/subjects/S-014/timeline')
  await page.getByLabel('Protocol actor').selectOption('medical reviewer')
  await expect(page.getByLabel('Medical review inbox')).toContainText('1 assigned to current actor')
  await page.getByRole('button', { name: 'Certify amendment' }).click()
  await expect(page.getByLabel('Medical review inbox')).toContainText('medical reviewer · completed')
  await page.getByRole('button', { name: 'Revalidate Visit 6' }).click()
  await page.goto('/studies/TF-201/subjects/S-014/readiness')
  await page.getByRole('button', { name: 'Authorize next visit' }).click()
  await expect(page.getByText('Next visit authorized')).toBeVisible()
})

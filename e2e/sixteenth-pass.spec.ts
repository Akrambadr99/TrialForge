import { expect, test } from '@playwright/test'

test('subject triage deep links survive reload and browser history', async ({ page }) => {
  await page.goto('/trial/subject-workspace?subject=S-015&q=TF-201&show=all&sort=id-desc&size=5')
  await expect(page.getByLabel('Search subjects')).toHaveValue('TF-201')
  await expect(page.getByLabel('Sort subjects')).toHaveValue('id-desc')
  await expect(page.getByLabel('Collection pages')).toContainText('4 matching records')
  await page.reload()
  await expect(page.getByLabel('Show', { exact: true })).toHaveValue('all')
  await page.getByLabel('Show', { exact: true }).selectOption('archived')
  await expect(page.getByLabel('Collection pages')).toContainText('1 matching records')
  await page.goBack()
  await expect(page.getByLabel('Show', { exact: true })).toHaveValue('all')
  await expect(page.getByLabel('Selected subject', { exact: true })).toContainText('S-015')
  await page.goForward()
  await expect(page.getByLabel('Show', { exact: true })).toHaveValue('archived')
})

test('subject details return to the exact collection context', async ({ page }) => {
  await page.goto('/trial/subject-workspace?subject=S-015&q=TF-201&state=unclaimed&sort=revision-desc&size=5&source=review')
  await page.getByRole('link', { name: 'Open record details' }).click()
  await page.reload()
  await page.getByRole('link', { name: 'Back to workspace' }).click()
  await expect(page.getByLabel('Search subjects')).toHaveValue('TF-201')
  await expect(page.getByLabel('Work state')).toHaveValue('unclaimed')
  await expect(page.getByLabel('Sort subjects')).toHaveValue('revision-desc')
  await expect(page).toHaveURL(/source=review/)
  await expect(page.getByLabel('Selected subject', { exact: true })).toContainText('S-015')
})

test('subject page selection remains explicit when filtering and resetting', async ({ page }) => {
  await page.setViewportSize({ width: 820, height: 1180 })
  await page.goto('/trial/subject-workspace?subject=S-015&show=all&size=5')
  await page.getByRole('button', { name: 'Select this page' }).click()
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.getByLabel('Bulk selection')).toContainText('5 subjects selected · 5 outside this page')
  await page.getByLabel('Select S-302', { exact: true }).check()
  await page.getByLabel('Search subjects').fill('does-not-exist')
  await expect(page.getByLabel('Bulk selection')).toContainText('6 subjects selected · 6 outside this page')
  await expect(page.getByLabel('Selected subject', { exact: true })).toContainText('outside this collection page or view')
  await page.getByRole('button', { name: 'Reset view' }).click()
  await expect(page.getByLabel('Collection pages')).toContainText('5 matching records · Page 1 of 1')
  await expect(page.getByLabel('Bulk selection')).toContainText('6 subjects selected · 1 outside this page')
  await page.screenshot({ path: '../UI_SCREENSHOTS/sixteenth-TrialForge-triage.png', fullPage: true })
  await page.getByRole('button', { name: 'Clear selection' }).click()
  await expect(page.getByRole('button', { name: 'Request selected medical reviews' })).toBeDisabled()
})

test('claiming a medical review updates triage without changing selected subject', async ({ page }) => {
  await page.goto('/trial/subject-workspace?subject=S-015&state=unclaimed')
  await page.getByRole('button', { name: 'Claim selected medical review' }).click()
  await expect(page.getByLabel('Collection pages')).toContainText('2 matching records')
  await expect(page.getByLabel('Selected subject', { exact: true })).toContainText('outside this collection page or view')
  await page.getByLabel('Work state').selectOption('claimed')
  await expect(page.getByLabel('Subject collection')).toContainText('Current review · claimed')
  await expect(page.getByLabel('Selected subject', { exact: true })).toContainText('S-015')
})
